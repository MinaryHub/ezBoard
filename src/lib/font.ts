/** 문자열을 선분 목록으로 변환. (x,y)는 왼쪽 위, h는 글자 높이 */
export function textStrokes(text: string, x: number, y: number, h: number): [number, number][][] {
  const s = h / 6;
  const adv = 5.5 * s;
  const out: [number, number][][] = [];
  [...text.toUpperCase()].forEach((ch, i) => {
    const glyph = G[ch];
    if (!glyph) return;
    for (const st of glyph) {
      const pl: [number, number][] = [];
      for (let k = 0; k < st.length; k += 2) pl.push([x + i * adv + st[k] * s, y + st[k + 1] * s]);
      out.push(pl);
    }
  });
  return out;
}

export function textWidth(text: string, h: number): number {
  return text.length * 5.5 * (h / 6) - 1.5 * (h / 6);
}
