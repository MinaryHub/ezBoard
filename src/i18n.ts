export type TKey = keyof typeof ko;
const DICTS: Record<Lang, Dict> = { ko, en };

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('ezboard.lang');
    if (saved === 'ko' || saved === 'en') return saved;
  } catch { /* 무시 */ }
  return (globalThis.navigator?.language || 'en').toLowerCase().startsWith('ko') ? 'ko' : 'en';
}

/** 문서 언어와 창 제목 */
function applyDocLang(lang: Lang) {
  if (typeof document === 'undefined') return; // 테스트(Node) 환경
  document.documentElement.lang = lang;
  document.title = lang === 'ko' ? 'ezBoard — AI PCB 설계' : 'ezBoard — AI PCB Design';
}

export const useLang = create<{ lang: Lang; setLang: (l: Lang) => void }>((set) => ({
  lang: initialLang(),
  setLang: (lang) => {
    try { localStorage.setItem('ezboard.lang', lang); } catch { /* 무시 */ }
    applyDocLang(lang);
    set({ lang });
  },
}));
applyDocLang(useLang.getState().lang);

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? ko[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** React 밖(스토어, 검사 등)에서 쓰는 번역 함수 */
export const t = (key: TKey, vars?: Record<string, string | number>) => translate(useLang.getState().lang, key, vars);

/** 컴포넌트용: 언어가 바뀌면 다시 그린다 */
export function useT() {
  const lang = useLang((s) => s.lang);
  return (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export const getLang = () => useLang.getState().lang;
